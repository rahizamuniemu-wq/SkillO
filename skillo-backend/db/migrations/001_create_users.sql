-- Enable the pgcrypto extension (needed for gen_random_uuid if UUID v4 is used)
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- users
-- =============================================================================
CREATE TABLE IF NOT EXISTS users (
    -- Primary key: UUID generated by the database
    id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Identity & auth
    email               TEXT        NOT NULL UNIQUE,
    password_hash       TEXT        NOT NULL,

    -- Profile – shared fields
    role                TEXT        NOT NULL CHECK (role IN ('worker', 'company')),
    first_name          TEXT        NOT NULL,
    last_name           TEXT        NOT NULL,
    points              INTEGER     NOT NULL DEFAULT 0,

    -- Worker-only profile fields (NULL for company accounts)
    university          TEXT,
    batch               TEXT,
    department          TEXT,
    skills              TEXT,           -- comma-separated e.g. "React,Node.js,Python"

    -- Company-only profile fields (NULL for worker accounts)
    company_name        TEXT,
    industry            TEXT,
    website             TEXT,
    description         TEXT,

    -- Email verification
    is_verified         BOOLEAN     NOT NULL DEFAULT FALSE,
    verify_code         CHAR(6),        -- 6-digit OTP; cleared after successful verification
    verify_code_exp     TIMESTAMPTZ,    -- expiry timestamp (15 minutes from issue)

    -- Audit
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- Indexes
-- =============================================================================

-- Fast lookup during login and verification flows
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users (email);

-- =============================================================================
-- Auto-update updated_at via trigger
-- =============================================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =============================================================================
-- Row Level Security (Supabase best practice)
-- We manage auth ourselves via JWT, so we disable RLS for this table.
-- If you later want Supabase Auth RLS, re-enable and add policies.
-- =============================================================================
ALTER TABLE users DISABLE ROW LEVEL SECURITY;
